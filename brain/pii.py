# -*- coding: utf-8 -*-
"""Скраббер персональных данных перед логом и аудитом. 152-ФЗ.

Почему это отдельный слой, а не «ну мы же аккуратно логируем». В переписке
стоматологии лежит худшая из возможных комбинаций: телефон пациента рядом с
жалобой «третий день ноет зуб, щеку раздуло». Телефон — идентификатор, жалоба —
**сведения о состоянии здоровья**, то есть особая категория ПД (152-ФЗ ст. 10).
Как только идентификатор и жалоба оказались в одной строке лога, файл логов
становится хранилищем медицинских данных со всеми вытекающими требованиями.
Разорвать связку дешевле, чем защищать хранилище: жалоба без телефона — не ПД,
она никого не идентифицирует.

Поэтому наружу (лог, аудит, Telegram-уведомления) текст идёт только через
`scrub()`. Оригинал живёт в переписке Авито — там он и должен жить, дублировать
его у себя незачем. В БД пишется `phone_hash()`, а не номер (см. CONTRACTS.md,
`brain/store/db.py`).

**Чего этот модуль НЕ умеет и не будет: кириллические имена.**
Регуляркой они не ловятся, и это не лень, а свойство языка. «Вера», «Люба»,
«Роман», «Рома», «Дима» — обычные слова и обычные имена одновременно; регистр
не помогает, потому что в чате пишут «здравствуйте вера ивановна» строчными, а
любое слово в начале фразы — с большой. Словарь имён либо промахивается по
редким, либо съедает нарицательные. Половинчатая ловилка имён хуже её
отсутствия: она создаёт ложное чувство защищённости, и на неё начинают
полагаться. Здесь честно ловятся телефоны и email — то, что ловится точно.
Также не ловятся: адреса, даты рождения, номера карт, СНИЛС, паспорта.

**Наши собственные номера — не ПД и не скрабятся.** Это не мелочь: назвать
пациенту телефон для звонка — главный призыв к действию во всей стратегии
продаж. Если скраббер съест наш номер, в логах и в уведомлениях администратору
исчезнет ровно то, что бот обязан говорить. Номера читаются из
`data/clinic-facts.json` (блок `phones`), а не из константы: они уже менялись
один раз за этот проект, и второй раз никто не вспомнит, что их копия лежит
в коде. Берётся каждая запись блока с полем `number`, а не только
`primary`/`secondary`, — чтобы третий номер заработал от правки данных.

Личная почта приходящего ортодонта из `clinic-facts.json` в белый список
намеренно НЕ входит: она помечена `status: internal`, её нельзя ни показывать
пациенту, ни оставлять в логах.

Известные ложные срабатывания (все — в сторону приватности, это осознанный
размен): голый прогон из 10 цифр считается телефоном, поэтому в логах будут
скрыты 10-значные id объявлений Авито и IP-адреса вида `100.100.10.10`.
Потерять id в логе дешевле, чем оставить в нём номер пациента.

Секреты (токены, ключи) здесь не обрабатываются сознательно: они не попадают
в лог вообще, потому что читаются из `os.environ` и никуда не печатаются, —
это дисциплина вызывающего кода, а не задача постфактум-фильтра.
"""
from __future__ import annotations

import hashlib
import json
import logging
import os
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

FACTS_PATH = Path(__file__).resolve().parent.parent / "data" / "clinic-facts.json"

PHONE_PLACEHOLDER = "[телефон]"
EMAIL_PLACEHOLDER = "[email]"
SCRUB_FAILED_PLACEHOLDER = "[запись скрыта: скраббер ПД недоступен]"

# Необязательный «перец» для phone_hash. Пусто по умолчанию — тогда хэш ровно
# такой, как в контракте: sha256 от нормализованного номера. См. phone_hash().
PEPPER_ENV = "PII_PHONE_PEPPER"
HASH_CHARS = 16
LOCAL_NUMBER_DIGITS = 7


# --- наши номера ------------------------------------------------------------

@lru_cache(maxsize=1)
def _facts() -> dict:
    with FACTS_PATH.open(encoding="utf-8") as fh:
        return json.load(fh)


@lru_cache(maxsize=1)
def own_phones() -> frozenset[str]:
    """Нормализованные номера клиники. Они не ПД и из текста не вырезаются."""
    numbers: set[str] = set()
    for entry in _facts()["phones"].values():
        if not isinstance(entry, dict):
            continue
        raw = entry.get("number")
        if not isinstance(raw, str):
            continue
        normalized = normalize_phone(raw)
        if normalized is not None:
            numbers.add(normalized)
    if not numbers:
        raise RuntimeError(
            "в clinic-facts.json нет ни одного разбираемого номера клиники; "
            "без белого списка скраббер вырежет наш собственный CTA"
        )
    return frozenset(numbers)


@lru_cache(maxsize=1)
def _own_local_tails() -> frozenset[str]:
    """Последние 7 цифр наших номеров — форма «555-35-35» без кода города.

    Самарцы пишут городской номер местной семёркой, и это наш основной CTA.
    Сравнение по хвосту применяется ТОЛЬКО к совпадениям без кода города:
    иначе чужой `+7 999 555-35-35` совпал бы хвостом с нашим и уцелел.
    """
    return frozenset(number[-LOCAL_NUMBER_DIGITS:] for number in own_phones())


# --- формы записи номера ----------------------------------------------------

# Разделители внутри номера. `\s` в Python уже покрывает неразрывный пробел
# (U+00A0) и узкий неразрывный (U+202F) — это категория Zs. А вот нулевой
# ширины (U+200B и родня) под `\s` не попадают, хотя регулярно приезжают
# копипастой с сайтов, поэтому перечислены явно. Тире тоже бывает не только
# ASCII-дефисом: пациенты вставляют U+2011 и U+2013 из Word.
_SEP = r"[\s()./\\‐-―−​‌‍⁠﻿-]{0,4}"
_DASH = r"[\s.‐-―−-]{1,2}"

# Полный номер: необязательный код страны + 10 цифр, разбитых как угодно.
# Группы по 3-3-2-2 при разделителе «ноль или больше символов» покрывают и
# `+7 999 123-45-67`, и `+79991234567`, и `8(999)123-45-67`, и `9991234567`
# одним выражением — разбивать на список форм не нужно, а лишние варианты
# только плодят дыры между собой. Границы `(?<!\d)`/`(?!\d)` не дают
# откусить 10 цифр из середины более длинного числа.
_PHONE = re.compile(
    rf"(?<!\d)(?:(?:\+{_SEP}7|7|8){_SEP})?"
    rf"\d{{3}}{_SEP}\d{{3}}{_SEP}\d{{2}}{_SEP}\d{{2}}(?!\d)"
)

# Местный номер без кода города: 555-35-35. Разделитель здесь ОБЯЗАТЕЛЕН —
# голые 7 цифр слишком похожи на сумму или id, а «5 000 000» скрабить нельзя.
_LOCAL = re.compile(rf"(?<!\d)\d{{3}}{_DASH}\d{{2}}{_DASH}\d{{2}}(?!\d)")

# `\w` здесь юникодный, поэтому ловится и `иван@почта.рф`.
_EMAIL = re.compile(r"[\w.%+\-]+@[\w\-]+(?:\.[\w\-]+)*\.\w{2,}")

_NON_DIGITS = re.compile(r"\D+")


def normalize_phone(raw: str) -> str | None:
    """Любая живая форма -> `+7XXXXXXXXXX`. None, если это не номер.

    Местная семёрка («555-35-35») возвращает None осознанно: код города по ней
    не восстановить, а угадать — значит записать пациенту чужой номер. Такой
    номер скрабится, но в `find_phones()` и `phone_hash()` не попадает.
    """
    digits = _NON_DIGITS.sub("", raw)
    if len(digits) == 11 and digits[0] in "78":
        return "+7" + digits[1:]
    if len(digits) == 10:
        return "+7" + digits
    return None


# --- разбор текста ----------------------------------------------------------

@dataclass(frozen=True)
class _Span:
    """Найденный фрагмент. `keep=True` — наш номер, остаётся как есть.

    Наши номера попадают в список наравне с чужими именно для того, чтобы
    занять место: иначе `_LOCAL` нашёл бы «555-35-35» внутри уже разобранного
    «+7 (800) 555-35-35» и вырезал середину нашего же CTA.
    """

    start: int
    end: int
    kind: str          # "phone" | "email"
    keep: bool
    value: str         # нормализованный номер; "" для email и местных форм


def _scan(text: str) -> tuple[_Span, ...]:
    """Единственный проход по тексту. На нём стоят scrub/find_phones/has_pii.

    Email разбирается первым: `ivan89991234567@mail.ru` содержит внутри себя
    валидный телефон, и без этого порядка адрес превратился бы в
    `ivan[телефон]@mail.ru` — а это всё ещё идентификатор.
    """
    spans: list[_Span] = []

    for match in _EMAIL.finditer(text):
        spans.append(_Span(match.start(), match.end(), "email", False, ""))

    for pattern in (_PHONE, _LOCAL):
        for match in pattern.finditer(text):
            if any(match.start() < s.end and s.start < match.end() for s in spans):
                continue
            raw = match.group(0)
            normalized = normalize_phone(raw)
            if normalized is not None:
                keep = normalized in own_phones()
            else:
                digits = _NON_DIGITS.sub("", raw)
                keep = digits in _own_local_tails()
            spans.append(_Span(match.start(), match.end(), "phone", keep, normalized or ""))

    return tuple(sorted(spans, key=lambda s: s.start))


def scrub(text: str) -> str:
    """Текст, годный для лога и аудита. Без ПД пациента, с нашими номерами.

    Если скрывать нечего, возвращается тот же объект: лог не должен ни
    переклеивать строки, ни трогать пробелы — расхождение байт в байт между
    оригиналом и «очищенным» текстом мешает потом сверять их глазами.
    """
    hidden = [s for s in _scan(text) if not s.keep]
    if not hidden:
        return text

    out: list[str] = []
    cursor = 0
    for span in hidden:
        out.append(text[cursor:span.start])
        out.append(PHONE_PLACEHOLDER if span.kind == "phone" else EMAIL_PLACEHOLDER)
        cursor = span.end
    out.append(text[cursor:])
    return "".join(out)


def find_phones(text: str) -> list[str]:
    """Номера пациента в нормальной форме, в порядке появления, без повторов.

    Наши собственные номера не возвращаются: функция нужна для детекции
    «пациент дал телефон», а наш CTA в его сообщении — это цитата, не лид.
    Один номер, написанный в трёх формах, даст одну запись.
    """
    found: list[str] = []
    for span in _scan(text):
        if span.kind == "phone" and not span.keep and span.value and span.value not in found:
            found.append(span.value)
    return found


def has_pii(text: str) -> bool:
    """Есть ли что скрывать. Ровно эквивалент `scrub(text) != text`."""
    return any(not span.keep for span in _scan(text))


def phone_hash(phone: str) -> str:
    """`sha256[:16]` от нормализованного номера — идентификатор лида для БД.

    Что это даёт: два сообщения с одним номером схлопываются в один лид, а сам
    номер в базе не лежит. Одна форма — один хэш, поэтому `+7 999 123-45-67` и
    `89991234567` неотличимы.

    Чего это НЕ даёт, и врать здесь нельзя: пространство российских номеров —
    10^10, полный перебор sha256 по нему занимает минуты на обычной видеокарте.
    Хэш защищает от случайного взгляда в базу и от утечки «сырых» номеров, но
    не от целенаправленного восстановления. Если это когда-нибудь станет
    важно — задайте `PII_PHONE_PEPPER` в окружении: значение подмешивается
    перед хэшированием, и перебор становится невозможен без него. По умолчанию
    переменной нет, и хэш ровно такой, как в контракте. Менять её на живой базе
    нельзя: все прошлые хэши перестанут совпадать.
    """
    normalized = normalize_phone(phone)
    if normalized is None:
        # В тексте исключения — ни одной цифры аргумента: исключения попадают
        # в логи, а лог — ровно то место, откуда ПД здесь и убирают.
        raise ValueError(
            "не удалось нормализовать номер: ожидались 10 или 11 цифр "
            "(само значение не выводится — персональные данные)"
        )
    pepper = os.environ.get(PEPPER_ENV, "")
    digest = hashlib.sha256((pepper + normalized).encode("utf-8")).hexdigest()
    return digest[:HASH_CHARS]


# --- logging ----------------------------------------------------------------

def _safe_scrub(text: str) -> str:
    """Скраб, который не умеет падать.

    Единственная реальная причина исключения здесь — недоступный или битый
    `clinic-facts.json`. Отдавать в этом случае исходный текст нельзя: это
    ровно тот момент, когда в лог уедут номера. Поэтому запись превращается в
    заглушку — потерять строку лога дешевле, чем утечь.
    """
    try:
        return scrub(text)
    except Exception:  # noqa: BLE001 — fail-closed, причина не важнее утечки
        return SCRUB_FAILED_PLACEHOLDER


class PiiLogFilter(logging.Filter):
    """Прогоняет записи лога через `scrub()`. Ставится на хендлер.

    Идея взята из `common/secret_redaction.py` в dvachbot, но там два изъяна,
    которые здесь исправлены.

    1. **Там `record.msg` подменяется всегда, а `record.args` скрабятся
       поштучно.** Аргумент, не являющийся str/int/float/bool, превращается в
       строку, и `%`-формат ломается: `log.info("сумма %.2f", Decimal("1.5"))`
       падает с TypeError, потому что до формата доезжает `"1.5"` вместо
       Decimal. Здесь сначала вызывается `record.getMessage()` — форматирование
       выполняется настоящими аргументами, как если бы фильтра не было, — и
       скрабится уже результат. `%d`, `%.2f`, `%r` и `__format__` работают
       ровно как без фильтра.

    2. **Там ленивое форматирование стирается у каждой записи.** Здесь запись
       не трогается вообще, если ПД в ней нет, — а это подавляющее большинство
       строк. Подмена `msg`/`args` происходит только по факту находки, и тогда
       она обязательна: оставить исходные `args` — значит дать следующему
       хендлеру собрать номер заново из «чистого» шаблона и грязных аргументов.

    Побочная выгода того же порядка действий: ловится ПД, которого нет ни в
    шаблоне, ни в аргументах по отдельности. `log.info("тел +7 999 %s-45-67",
    "123")` — полный номер существует только после склейки, и фильтр dvachbot
    его пропускает, а этот видит.

    Чего фильтр не делает: не разбирает traceback (`exc_info`). Готовый
    `exc_text`, если формат уже успел его собрать, скрабится; но исключение,
    в repr которого попал номер, надёжно вычистить на этом уровне нельзя —
    не кладите ПД в текст исключений, для этого есть `phone_hash()`.
    """

    def filter(self, record: logging.LogRecord) -> bool:
        try:
            rendered = record.getMessage()
        except Exception:  # noqa: BLE001 — битый формат не должен глотать запись
            cleaned = _safe_scrub(str(record.msg))
            if cleaned != str(record.msg):
                record.msg = cleaned
            return True

        cleaned = _safe_scrub(rendered)
        if cleaned != rendered:
            record.msg = cleaned
            record.args = ()

        if record.exc_text:
            record.exc_text = _safe_scrub(record.exc_text)
        return True


_FILTER = PiiLogFilter()


def attach(handler: logging.Handler) -> None:
    """Поставить скраббер на конкретный хендлер."""
    handler.addFilter(_FILTER)


def install(logger: logging.Logger | None = None) -> None:
    """Поставить скраббер на все хендлеры логгера (по умолчанию — корневого).

    Фильтр вешается именно на хендлеры, а не на логгер. `Logger.addFilter`
    выглядит надёжнее, но обрабатывает только записи, созданные на самом этом
    логгере: всё, что пришло по цепочке propagate от `logging.getLogger(
    "brain.router")`, мимо него проходит нетронутым. В dvachbot фильтр
    добавлен и на корневой логгер тоже — эта половина там не работает.
    """
    target = logger or logging.getLogger()
    for handler in target.handlers:
        attach(handler)
