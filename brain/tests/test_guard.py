def run() -> int:
    failures: list[str] = []

    print(f"разрешённые суммы: {sorted(guard.allowed_amounts())}\n")

    print("--- извлечение сумм ---")
    for text, want in AMOUNT_CASES:
        got = sorted(guard.money_amounts(text))
        ok = got == sorted(want)
        if not ok:
            failures.append(f"суммы {text!r}: ждали {want}, получили {got}")
        print(f"  {'ок  ' if ok else 'ФЕЙЛ'} {text[:46]:<46} -> {got}")

    print("\n--- должны проходить ---")
    for text in PASS_CASES:
        verdict = guard.check(text)
        if not verdict.ok:
            failures.append(f"ложное срабатывание: {text[:50]!r} -> {verdict.reason}")
        print(f"  {'ок  ' if verdict.ok else 'ФЕЙЛ'} {text[:60]}"
              f"{'' if verdict.ok else chr(10) + '        ' + verdict.reason}")

    print("\n--- должны быть заветированы ---")
    for text, why in VETO_CASES:
        verdict = guard.check(text)
        if verdict.ok:
            failures.append(f"ПРОПУСК: {why} — {text[:60]!r}")
        print(f"  {'ок  ' if not verdict.ok else 'ПРОПУСК'} {why}")
        if not verdict.ok:
            print(f"        {verdict.reason}")

    total = len(AMOUNT_CASES) + len(PASS_CASES) + len(VETO_CASES)
    print(f"\nИТОГ: {total - len(failures)}/{total}")
    for f in failures:
        print(f"  {f}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(run())
